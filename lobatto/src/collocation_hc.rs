// Unique absolute values |D[i,j]| for rows 0,1,2,3, generated by
// `cargo run --bin gen_q6`.  Integer-valued entries (±21, ±1) are inlined
// directly in the kernel.
const DX6: [f64; 20] = [
    28.40315320583964009415, // |D[0,1]|
    11.33797045109102263893, // |D[0,2]|
    6.39999999999999680256,  // |D[0,3]|
    4.09992962615348588429,  // |D[0,4]|
    2.63474687140487073833,  // |D[0,5]|
    4.88585202848857402813,  // |D[1,0]|
    6.91165642858857065534,  // |D[1,2]|
    3.19721337619673073860,  // |D[1,3]|
    1.92267959457742243501,  // |D[1,4]|
    1.20449435927157155746,  // |D[1,5]|
    0.45322374079089045029,  // |D[1,6]|
    1.25051333103068440522,  // |D[2,0]|
    4.43160856633994804099,  // |D[2,1]|
    4.53339617417199303162,  // |D[2,3]|
    2.13288380801274835008,  // |D[2,4]|
    1.23278167103515956526,  // |D[2,5]|
    0.45219880188514915975,  // |D[2,6]|
    0.62500000000000022204,  // |D[3,0]|
    1.81508894253764396787,  // |D[3,1]|
    4.01393848117750717819,  // |D[3,2]|
];

/// 1D Q6 differentiation kernel for a batch of `N` elements.
///
/// The stride `M` selects the differentiation direction:
///   - `M = 1`  → x  (7 nodes, consecutive)
///   - `M = 7`  → y  (stride 7)
///   - `M = 49` → z  (stride 49)
///
/// Rows 4,5,6 exploit the antisymmetry D[6-i, 6-j] = -D[i,j].
/// Each output loop is kept independent to enable auto-vectorization over N.
fn _d_q6_q6<const N: usize, const M: usize>(in_q6: &[f64], out_q6: &mut [f64]) {
    let a = &in_q6[0..N];
    let b = &in_q6[M * N..M * N + N];
    let c = &in_q6[2 * M * N..2 * M * N + N];
    let d = &in_q6[3 * M * N..3 * M * N + N];
    let e = &in_q6[4 * M * N..4 * M * N + N];
    let f = &in_q6[5 * M * N..5 * M * N + N];
    let g = &in_q6[6 * M * N..6 * M * N + N];

    for i in 0..N {
        out_q6[i] = -21.0 * a[i] + DX6[0] * b[i] - DX6[1] * c[i] + DX6[2] * d[i] - DX6[3] * e[i]
            + DX6[4] * f[i]
            - 1.0 * g[i];
    }
    for i in 0..N {
        out_q6[1 * M * N + i] = -DX6[5] * a[i] + DX6[6] * c[i] - DX6[7] * d[i] + DX6[8] * e[i]
            - DX6[9] * f[i]
            + DX6[10] * g[i];
    }
    for i in 0..N {
        out_q6[2 * M * N + i] = DX6[11] * a[i] - DX6[12] * b[i] + DX6[13] * d[i] - DX6[14] * e[i]
            + DX6[15] * f[i]
            - DX6[16] * g[i];
    }
    for i in 0..N {
        out_q6[3 * M * N + i] = -DX6[17] * a[i] + DX6[18] * b[i] - DX6[19] * c[i] + DX6[19] * e[i]
            - DX6[18] * f[i]
            + DX6[17] * g[i];
    }
    for i in 0..N {
        out_q6[4 * M * N + i] = DX6[16] * a[i] - DX6[15] * b[i] + DX6[14] * c[i] - DX6[13] * d[i]
            + DX6[12] * f[i]
            - DX6[11] * g[i];
    }
    for i in 0..N {
        out_q6[5 * M * N + i] = -DX6[10] * a[i] + DX6[9] * b[i] - DX6[8] * c[i] + DX6[7] * d[i]
            - DX6[6] * e[i]
            + DX6[5] * g[i];
    }
    for i in 0..N {
        out_q6[6 * M * N + i] = 1.0 * a[i] - DX6[4] * b[i] + DX6[3] * c[i] - DX6[2] * d[i]
            + DX6[1] * e[i]
            - DX6[0] * f[i]
            + 21.0 * g[i];
    }
}

