//! Hardcoded SIMD-friendly operations for Q3–Q6 elements in dimension up to 3.
//!
//! Each operator applies the 1D spectral differentiation matrix **D** to a
//! batch of `N` elements simultaneously, exploiting the antisymmetry of the
//! GLL differentiation matrix to halve the number of unique coefficients.
//! Multi-dimensional operators (2D and 3D) are built by sum-factorisation,
//! applying the 1D kernel direction by direction.
//!
//! For a batch of `N` elements, node `g` of element `e` is stored at index
//! `g*M*N + e`, where `M` is the stride between consecutive nodes in the
//! chosen direction.

// ============================================================================
// Q3  (4 nodes, degree 3)
// ============================================================================

// Unique absolute values |D[i,j]| for rows 0,1, generated by
// `cargo run --bin gen_q3`.  Integer-valued entries (±6, ±1) are inlined
// directly in the kernel.
const DX3: [f64; 5] = [
    8.09016994374947451263, // |D[0,1]|
    3.09016994374947362445, // |D[0,2]|
    1.61803398874989490253, // |D[1,0]|
    2.23606797749978936096, // |D[1,2]|
    0.61803398874989479150, // |D[1,3]|
];

/// 1D Q3 differentiation kernel for a batch of `N` elements.
///
/// The stride `M` selects the differentiation direction:
///   - `M = 1`  → x  (4 nodes, consecutive)
///   - `M = 4`  → y  (stride 4)
///   - `M = 16` → z  (stride 16)
///
/// Rows 2,3 exploit the antisymmetry D[3-i, 3-j] = -D[i,j].
/// Each output loop is kept independent to enable auto-vectorization over N.
fn _d_q3_q3<const N: usize, const M: usize>(in_q3: &[f64], out_q3: &mut [f64]) {
    let a = &in_q3[0..N];
    let b = &in_q3[M * N..M * N + N];
    let c = &in_q3[2 * M * N..2 * M * N + N];
    let d = &in_q3[3 * M * N..3 * M * N + N];

    for i in 0..N {
        out_q3[i] = -6.0 * a[i] + DX3[0] * b[i] - DX3[1] * c[i] + 1.0 * d[i];
    }
    for i in 0..N {
        out_q3[1 * M * N + i] = -DX3[2] * a[i] + DX3[3] * c[i] - DX3[4] * d[i];
    }
    for i in 0..N {
        out_q3[2 * M * N + i] = DX3[4] * a[i] - DX3[3] * b[i] + DX3[2] * d[i];
    }
    for i in 0..N {
        out_q3[3 * M * N + i] = -1.0 * a[i] + DX3[1] * b[i] - DX3[0] * c[i] + 6.0 * d[i];
    }
}

// ----------------------------------------------------------------------------
// 1D  —  Q3  (4*N dofs)
// ----------------------------------------------------------------------------

/// x-derivative on a batch of N Q3 elements (4*N dofs).
pub fn dx_q3_q3<const N: usize>(input: &[f64], output: &mut [f64]) {
    _d_q3_q3::<N, 1>(&input[0..N * 4], &mut output[0..N * 4]);
}

