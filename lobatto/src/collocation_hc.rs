/// 1D Q5 transpose differentiation kernel for a batch of `N` elements.
///
/// Applies $(D^{(Q5)})^\top$ fibre-by-fibre; same stride convention as [`_d_q5_q5`].
/// Coefficients reuse DX5 with permuted indices, by antisymmetry of D.
fn _d_t_q5_q5<const N: usize, const M: usize>(in_q5: &[f64], out_q5: &mut [f64]) {
    let a = &in_q5[0..N];
    let b = &in_q5[M * N..M * N + N];
    let c = &in_q5[2 * M * N..2 * M * N + N];
    let d = &in_q5[3 * M * N..3 * M * N + N];
    let e = &in_q5[4 * M * N..4 * M * N + N];
    let f = &in_q5[5 * M * N..5 * M * N + N];

    for i in 0..N {
        out_q5[i] = -15.0 * a[i] - DX5[4] * b[i] + DX5[9] * c[i] - DX5[13] * d[i] + DX5[8] * e[i]
            - 1.0 * f[i];
    }
    for i in 0..N {
        out_q5[1 * M * N + i] =
            DX5[0] * a[i] - DX5[10] * c[i] + DX5[12] * d[i] - DX5[7] * e[i] + DX5[3] * f[i];
    }
    for i in 0..N {
        out_q5[2 * M * N + i] =
            -DX5[1] * a[i] + DX5[5] * b[i] - DX5[11] * d[i] + DX5[6] * e[i] - DX5[2] * f[i];
    }
    for i in 0..N {
        out_q5[3 * M * N + i] =
            DX5[2] * a[i] - DX5[6] * b[i] + DX5[11] * c[i] - DX5[5] * e[i] + DX5[1] * f[i];
    }
    for i in 0..N {
        out_q5[4 * M * N + i] =
            -DX5[3] * a[i] + DX5[7] * b[i] - DX5[12] * c[i] + DX5[10] * d[i] - DX5[0] * f[i];
    }
    for i in 0..N {
        out_q5[5 * M * N + i] = 1.0 * a[i] - DX5[8] * b[i] + DX5[13] * c[i] - DX5[9] * d[i]
            + DX5[4] * e[i]
            + 15.0 * f[i];
    }
}

