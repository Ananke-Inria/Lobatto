/// 1D Q5 differentiation kernel for a batch of `N` elements.
///
/// The stride `M` selects the differentiation direction:
///   - `M = 1`  → x  (6 nodes, consecutive)
///   - `M = 6`  → y  (stride 6)
///   - `M = 36` → z  (stride 36)
///
/// Rows 3,4,5 exploit the antisymmetry D[5-i, 5-j] = -D[i,j].
/// Each output loop is kept independent to enable auto-vectorization over N.
fn _d_q5_q5<const N: usize, const M: usize>(in_q5: &[f64], out_q5: &mut [f64]) {
    let a = &in_q5[0..N];
    let b = &in_q5[M * N..M * N + N];
    let c = &in_q5[2 * M * N..2 * M * N + N];
    let d = &in_q5[3 * M * N..3 * M * N + N];
    let e = &in_q5[4 * M * N..4 * M * N + N];
    let f = &in_q5[5 * M * N..5 * M * N + N];

    for i in 0..N {
        out_q5[i] =
            -15.0 * a[i] + DX5[0] * b[i] - DX5[1] * c[i] + DX5[2] * d[i] - DX5[3] * e[i] + f[i];
    }
    for i in 0..N {
        out_q5[M * N + i] =
            -DX5[4] * a[i] + DX5[5] * c[i] - DX5[6] * d[i] + DX5[7] * e[i] - DX5[8] * f[i];
    }
    for i in 0..N {
        out_q5[2 * M * N + i] =
            DX5[9] * a[i] - DX5[10] * b[i] + DX5[11] * d[i] - DX5[12] * e[i] + DX5[13] * f[i];
    }
    for i in 0..N {
        out_q5[3 * M * N + i] =
            -DX5[13] * a[i] + DX5[12] * b[i] - DX5[11] * c[i] + DX5[10] * e[i] - DX5[9] * f[i];
    }
    for i in 0..N {
        out_q5[4 * M * N + i] =
            DX5[8] * a[i] - DX5[7] * b[i] + DX5[6] * c[i] - DX5[5] * d[i] + DX5[4] * f[i];
    }
    for i in 0..N {
        out_q5[5 * M * N + i] =
            -a[i] + DX5[3] * b[i] - DX5[2] * c[i] + DX5[1] * d[i] - DX5[0] * e[i] + 15.0 * f[i];
    }
}

